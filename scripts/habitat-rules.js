// 返回生境违规列表;空数组表示合规。
export function habitatIssues(habitat) {
  const h = String(habitat ?? '');
  if (!h.trim()) return ['生境为空'];
  const issues = [];
  if (/[A-Za-z]/.test(h)) issues.push('含英文/拉丁字符');
  if (/[0-9]/.test(h)) issues.push('含数字(如海拔/区间)');
  if (/[（()）\[\]]/.test(h)) issues.push('含括号');
  for (const w of HABITAT_FORBIDDEN_WORDS) {
    if (h.includes(w)) issues.push(`含非生境用词「${w}」`);
  }
  for (const r of HABITAT_REGION_WORDS) {
    if (h.includes(r)) issues.push(`含地区「${r}」`);
  }
  return issues;
}
